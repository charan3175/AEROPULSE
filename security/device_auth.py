"""
AERO-SENTINEL Device Authentication

Prototype purpose:
Verify that telemetry is coming from a registered engine/device.

This is an application-level prototype.
It is NOT a replacement for certified hardware security.
"""

import hashlib
import hmac
from typing import Dict


# -------------------------------------------------------------------
# Registered devices
# -------------------------------------------------------------------

REGISTERED_DEVICES = {
    "UAV-ENGINE-001": {
        "device_name": "MALE UAV Engine 001",
        "device_type": "AERO_PISTON_ENGINE",
        "status": "ACTIVE",
        "secret": "AERO_SENTINEL_ENGINE_001_SECRET",
    },

    "UAV-ENGINE-002": {
        "device_name": "MALE UAV Engine 002",
        "device_type": "AERO_PISTON_ENGINE",
        "status": "ACTIVE",
        "secret": "AERO_SENTINEL_ENGINE_002_SECRET",
    },
}


# -------------------------------------------------------------------
# Generate device signature
# -------------------------------------------------------------------

def generate_device_signature(
    device_id: str,
    message: str,
) -> str:
    """
    Generate an HMAC-SHA256 signature for a telemetry message.

    The device secret is used to prove that the message
    was generated by a registered device.
    """

    device = REGISTERED_DEVICES.get(device_id)

    if device is None:
        raise ValueError("Unknown device")

    secret = device["secret"].encode("utf-8")
    message_bytes = message.encode("utf-8")

    signature = hmac.new(
        secret,
        message_bytes,
        hashlib.sha256,
    ).hexdigest()

    return signature


# -------------------------------------------------------------------
# Authenticate device
# -------------------------------------------------------------------

def authenticate_device(
    device_id: str,
    message: str,
    signature: str,
) -> Dict:
    """
    Authenticate a device and verify message signature.
    """

    device = REGISTERED_DEVICES.get(device_id)

    if device is None:
        return {
            "authenticated": False,
            "device_id": device_id,
            "status": "REJECTED",
            "reason": "Unknown device.",
        }

    if device["status"] != "ACTIVE":
        return {
            "authenticated": False,
            "device_id": device_id,
            "status": "REJECTED",
            "reason": "Device is not active.",
        }

    expected_signature = generate_device_signature(
        device_id,
        message,
    )

    valid_signature = hmac.compare_digest(
        expected_signature,
        signature,
    )

    if not valid_signature:
        return {
            "authenticated": False,
            "device_id": device_id,
            "status": "REJECTED",
            "reason": "Invalid telemetry signature.",
        }

    return {
        "authenticated": True,
        "device_id": device_id,
        "device_name": device["device_name"],
        "device_type": device["device_type"],
        "status": "AUTHENTICATED",
        "reason": "Device and telemetry signature verified.",
    }


